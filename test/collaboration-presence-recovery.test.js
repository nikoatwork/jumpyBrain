test("presence follows canonical inserts, rebases delayed packets, rejects epoch/future/gap and same-revision reorder",async(t)=>{
  const {hub}=await fixture(t);
  const first=await hub.open(documentId,alice,{clientId:"tab"});
  await hub.dispatch("presence",{...params(first),selection:{anchor:4,focus:4},presenceSequence:1},alice);
  const saved=await hub.dispatch("edit",{...params(first,"bob"),operationId:"before",start:0,deleteCount:0,insert:"NEW "},bob);
  assert.equal(saved.presence.find(p=>p.principalId==="alice").anchor,8);
  const delayed=await hub.dispatch("presence",{...params(first),selection:{anchor:5,focus:5},presenceSequence:2},alice);
  assert.equal(delayed.presence.find(p=>p.principalId==="alice").anchor,9);
  await assert.rejects(hub.dispatch("presence",{...params(saved),selection:{anchor:0,focus:0},presenceSequence:1},alice),e=>e.code==="stale_presence");
  await hub.dispatch("presence",{...params(saved),selection:{anchor:9,focus:9},presenceSequence:3},alice);
  await assert.rejects(hub.dispatch("presence",{...params(first),selection:{anchor:5,focus:5},presenceSequence:4},alice),e=>e.code==="stale_presence");
  const blurred=await hub.dispatch("presence",{...params(saved),activity:"viewing",presenceSequence:5},alice);
  assert.equal(blurred.presence.find(peer=>peer.principalId===alice.id).anchor,undefined);
  assert.equal(blurred.presence.find(peer=>peer.principalId===alice.id).activity,"viewing");
  await assert.rejects(hub.dispatch("presence",{...params(saved),selection:{anchor:8,focus:8},presenceSequence:4},alice),e=>e.code==="stale_presence");
  await assert.rejects(hub.dispatch("presence",{...params(saved),epoch:"previous-runtime",selection:{anchor:0,focus:0}},alice),e=>e.code==="epoch_changed");
  await assert.rejects(hub.dispatch("presence",{...params(saved),baseRevision:999,selection:{anchor:0,focus:0}},alice),e=>e.code==="invalid_revision");
  // Retain the same person appearance across distinct tab/undo identities.
  const tab=await hub.open(documentId,alice,{clientId:"new-tab"});
  const peers=tab.presence.filter(p=>p.principalId==="alice");
  assert.equal(new Set(peers.map(p=>p.actor)).size,2);
  assert.equal(new Set(peers.map(p=>p.principalId)).size,1);
});
