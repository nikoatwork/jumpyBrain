test("raw replacements expose hash-gated retained copies to readers across restart, reject traversal, tampering and symlinks",async(t)=>{
  const f=await fixture(t);
  const before=await f.hub.open(documentId,alice,{clientId:"tab"});
  const prior=await readFile(f.file,"utf8");
  await writeFile(f.file,content("raw replacement\n"));
  await f.hub.observe();
  let s=await f.hub.read(documentId);
  assert.equal(s.saved,true);assert.equal(s.recovery.code,"external_destructive_replacement");
  const request={documentId,recoveryId:s.recovery.recoveryId,expectedBaseHash:s.recovery.baseContentHash,expectedExternalHash:s.recovery.externalContentHash};
  let copies=await f.hub.readRecovery(request,reader);
  assert.equal(copies.base.content,prior);
  assert.equal(copies.external.content,await readFile(f.file,"utf8"));
  assert.equal(copies.currentContentHash,s.contentHash);
  assert.equal(JSON.stringify(copies).includes(f.root),false);
  await assert.rejects(f.hub.readRecovery({...request,recoveryId:"../../access.json"},reader),e=>e.code==="invalid_recovery");
  await assert.rejects(f.hub.readRecovery({...request,expectedBaseHash:before.contentHash+"0"},reader),e=>e.code==="recovery_changed");
  await f.restart();
  s=await f.hub.open(documentId,reader,{clientId:"reader"});
  assert.equal(s.recovery.recoveryId,request.recoveryId);
  copies=await f.hub.readRecovery(request,reader);assert.equal(copies.base.content,prior);
  const retained=path.join(f.root,s.recovery.directory,"base.md");
  await writeFile(retained,"corrupt");
  await assert.rejects(f.hub.readRecovery(request,reader),e=>e.code==="unsafe_recovery");
  await rm(retained);await symlink(f.file,retained);
  await assert.rejects(f.hub.readRecovery(request,reader));
  assert.equal((await readFile(f.file,"utf8")).endsWith("raw replacement\n"),true);
});
test("real WS recovery reads require an open authenticated scope, readers cannot restore, revocation removes presence",async(t)=>{
  const f=await fixture(t);
  await f.hub.open(documentId,alice,{clientId:"writer"});
  await writeFile(f.file,content("external authoritative\n"));await f.hub.observe();
  const snapshot=await f.hub.read(documentId);
  const access=new AccessStore(f.root);
  const issued=await access.issue({name:"Review reader",role:"reader"});
  const server=createServer((_req,res)=>res.end());
  const live=createLiveServer({server,hub:f.hub,authenticate:credential=>access.authenticate(credential),revalidateIntervalMs:15});
  server.listen(0,"127.0.0.1");await once(server,"listening");
  const ws=new WebSocket(`ws://127.0.0.1:${server.address().port}/ws`);
  t.after(async()=>{ws.terminate();await live.close();await new Promise(resolve=>server.close(resolve));access.close();});
  await once(ws,"open");
  let sequence=0;
  const waiting=new Map();
  ws.on("message",data=>{const packet=JSON.parse(data.toString());const pending=waiting.get(packet.id);if(pending){waiting.delete(packet.id);clearTimeout(pending.timer);pending.resolve(packet);}});
  const rpc=(method,params)=>new Promise((resolve,reject)=>{const id=String(++sequence);waiting.set(id,{resolve,timer:setTimeout(()=>{waiting.delete(id);reject(new Error("RPC deadline"));},1500)});ws.send(JSON.stringify({id,method,params}));});
  assert.equal((await rpc("hello",{protocol:2,token:issued.token})).ok,true);
  const request={documentId,clientId:"reader",recoveryId:snapshot.recovery.recoveryId,expectedBaseHash:snapshot.recovery.baseContentHash,expectedExternalHash:snapshot.recovery.externalContentHash};
  assert.equal((await rpc("recovery.read",request)).error.code,"document_not_open");
  const opened=await rpc("open",{documentId,clientId:"reader"});assert.equal(opened.ok,true);
  const result=await rpc("recovery.read",request);assert.equal(result.ok,true);assert.equal(result.result.external.content,content("external authoritative\n"));
  assert.equal((await rpc("recovery.read",{...request,clientId:"different-tab"})).error.code,"document_not_open");
  assert.equal((await rpc("edit",{...params(opened.result,"reader"),operationId:"unauthorized-restore",start:0,deleteCount:opened.result.body.length,insert:"restore"})).error.code,"forbidden");
  const closed=once(ws,"close");await access.revoke(issued.credential.id);assert.equal((await closed)[0],1008);
  assert.equal((await f.hub.read(documentId)).presence.some(peer=>peer.principalId===issued.credential.id),false);
  assert.equal((await readFile(f.file,"utf8")).endsWith("external authoritative\n"),true);
});
