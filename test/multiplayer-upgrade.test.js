import assert from 'node:assert/strict';
import test from 'node:test';
import { spawnSync } from 'node:child_process';
import { mkdtemp, mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { fileURLToPath } from 'node:url';
import { ensureRootBackend, backendStatus, stopRootBackend } from '../dist/app/backend-host/index.js';
import { AccessStore } from '../dist/adapters/access-control/index.js';

const repository=fileURLToPath(new URL('..',import.meta.url)), script=path.join(repository,'scripts/multiplayer-upgrade.mjs');
const run=(...args)=>spawnSync(process.execPath,[script,...args],{encoding:'utf8',timeout:15000});
test('coordinated upgrade previews, privately backs up, stops owner, verifies exact bytes and safely restores missing files', {timeout:30000}, async t=>{
  const temporary=await mkdtemp(path.join(os.tmpdir(),'jumpybrain-upgrade-')),root=path.join(temporary,'brain'),backup=path.join(temporary,'backup');
  await mkdir(root);t.after(async()=>{await stopRootBackend(root).catch(()=>{});await rm(temporary,{recursive:true,force:true});});
  const policy='{"schemaVersion":1,"indexing":{"mode":"lexical"}}\n';
  await writeFile(path.join(root,'jumpybrain.json'),policy);await writeFile(path.join(root,'note.md'),'# Original\n');
  const store=new AccessStore(root);t.after(()=>store.close());const issued=await store.issue({name:'Independent agent',role:'writer'});
  await mkdir(path.join(root,'.jumpybrain/recovery/note/candidate'),{recursive:true,mode:0o700});
  await writeFile(path.join(root,'.jumpybrain/recovery/note/candidate/draft.md'),'recoverable private draft',{mode:0o600});
  const preview=run('--root',root,'--mode','prepare','--backup',backup);
  assert.equal(preview.status,0,preview.stderr);assert.equal(JSON.parse(preview.stdout).dryRun,true);
  await assert.rejects(stat(backup),{code:'ENOENT'});
  await ensureRootBackend(root);
  const prepare=run('--root',root,'--mode','prepare','--backup',backup,'--apply');
  assert.equal(prepare.status,0,prepare.stderr);assert.equal(JSON.parse(prepare.stdout).complete,true);assert.equal(JSON.parse(prepare.stdout).stopped,true);
  assert.equal((await backendStatus(root)).status,'stopped');assert.equal((await stat(backup)).mode&0o077,0);
  assert.equal((prepare.stdout+prepare.stderr).includes(issued.token),false);
  const manifest=JSON.parse(await readFile(path.join(backup,'manifest.json'),'utf8'));
  assert.equal(manifest.files.some(item=>item.path.includes('backend/connection')),false);
  assert.equal(manifest.files.filter(item=>item.kind==='operational').length,2);
  const verify=run('--root',root,'--mode','verify','--backup',backup,'--app-runtime',repository);
  assert.equal(verify.status,0,verify.stderr);assert.equal(JSON.parse(verify.stdout).builds.appChecked,true);
  await writeFile(path.join(root,'note.md'),'# Changed\n');
  assert.equal(run('--root',root,'--mode','verify','--backup',backup).status,1);
  assert.equal(run('--root',root,'--mode','restore','--backup',backup,'--apply').status,1);
  assert.equal(await readFile(path.join(root,'note.md'),'utf8'),'# Changed\n');
  await rm(path.join(root,'note.md'));
  const restore=run('--root',root,'--mode','restore','--backup',backup,'--apply');
  assert.equal(restore.status,0,restore.stderr);assert.equal(JSON.parse(restore.stdout).restoredFiles,1);
  assert.equal(await readFile(path.join(root,'note.md'),'utf8'),'# Original\n');
  assert.equal(await readFile(path.join(root,'jumpybrain.json'),'utf8'),policy);
  await store.revoke(issued.credential.id);
  assert.equal(run('--root',root,'--mode','restore','--backup',backup,'--apply').status,1);
  assert.equal(await store.authenticate(issued.token),undefined);
});
test('upgrade helper reports build mismatch, refuses nested backups and verifies backup hashes', async t=>{
  const temporary=await mkdtemp(path.join(os.tmpdir(),'jumpybrain-upgrade-safe-')),root=path.join(temporary,'brain'),backup=path.join(temporary,'backup'),app=path.join(temporary,'app');
  t.after(()=>rm(temporary,{recursive:true,force:true}));await mkdir(root);await writeFile(path.join(root,'note.md'),'# Existing\n');
  await mkdir(path.join(app,'dist/adapters/diagnostics'),{recursive:true});await writeFile(path.join(app,'dist/adapters/diagnostics/build-info.json'),'{"version":"0.0.0","build":"different"}');
  const status=run('--root',root,'--app-runtime',app);assert.equal(status.status,0,status.stderr);assert.equal(JSON.parse(status.stdout).builds.matching,false);
  assert.equal(run('--root',root,'--mode','prepare','--backup',path.join(root,'backup'),'--apply').status,1);
  assert.equal(run('--root',root,'--mode','prepare','--backup',backup,'--apply').status,0);
  assert.equal(run('--root',root,'--mode','verify','--backup',backup,'--app-runtime',app).status,1);
  await writeFile(path.join(backup,'files/note.md'),'tampered');
  assert.equal(run('--root',root,'--mode','verify','--backup',backup).status,1);
  assert.equal(await readFile(path.join(root,'note.md'),'utf8'),'# Existing\n');
});
