import assert from 'node:assert/strict';
import test from 'node:test';
import {mkdtemp,rm,writeFile} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {once} from 'node:events';
import {WebSocket} from 'ws';
import {initializeMemoryRoot} from '../dist/runtime/index.js';
import {startJumpyBrainHttpServer} from '../dist/server/index.js';
import {AccessStore} from '../dist/adapters/access-control/index.js';
const id='mem_57777777-7777-4777-8777-777777777777';
test('hosted HttpOnly sessions survive reload/restart, enforce origin and revoke HTTP plus WS access',async t=>{
  const root=await mkdtemp(path.join(os.tmpdir(),'jb-browser-session-'));await initializeMemoryRoot(root);
  await writeFile(path.join(root,'notes/session.md'),`---\nid: ${id}\ntitle: Browser session\ntype: note\n---\nSaved source\n`);
  const access=new AccessStore(root),issued=await access.issue({name:'Human session',role:'writer'});
  let server=await startJumpyBrainHttpServer({root,apiKeys:['disposable-operator'],port:0,autoIndex:false});
  t.after(async()=>{access.close();await server.close();await rm(root,{recursive:true,force:true,maxRetries:5,retryDelay:50});});
  const session=await fetch(server.url+'/session',{headers:{Authorization:'Bearer '+issued.token}});
  assert.equal(session.status,200);const header=session.headers.get('set-cookie');
  assert.match(header,/HttpOnly/);assert.match(header,/SameSite=Strict/);assert.match(header,/Max-Age=86400/);
  const cookie=header.split(';')[0];const packet=await session.json();assert.equal(packet.principal.id,issued.credential.id);assert.doesNotMatch(JSON.stringify(packet),new RegExp(issued.token));
  const status=await fetch(server.url+'/session',{headers:{Cookie:cookie}});assert.equal(status.status,200);
  const badOrigin=await fetch(server.url+'/memories/all/notes',{method:'POST',headers:{Cookie:cookie,Origin:'https://untrusted.example','content-type':'application/json'},body:JSON.stringify({type:'note',body:'must not publish'})});assert.equal(badOrigin.status,403);
  const port=new URL(server.url).port;await server.close();
  server=await startJumpyBrainHttpServer({root,apiKeys:['disposable-operator'],port:Number(port),autoIndex:false});
  assert.equal((await fetch(server.url+'/session',{headers:{Cookie:cookie}})).status,200,'a valid credential session survives a backend restart');
  const socket=new WebSocket(server.url.replace(/^http/,'ws')+'/ws',{headers:{Cookie:cookie,Origin:server.url}});await once(socket,'open');
  t.after(()=>socket.terminate());
  const reply=once(socket,'message');socket.send(JSON.stringify({id:'hello',method:'hello',params:{protocol:2,token:'browser-session'}}));assert.equal(JSON.parse(String((await reply)[0])).ok,true);
  await access.revoke(issued.credential.id);
  assert.equal((await fetch(server.url+'/session',{headers:{Cookie:cookie}})).status,401);
  await once(socket,'close');
  const logout=await fetch(server.url+'/session',{method:'DELETE',headers:{Origin:server.url,Cookie:cookie}});assert.equal(logout.status,200);assert.match(logout.headers.get('set-cookie'),/Max-Age=0/);
});
