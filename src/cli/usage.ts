export function usage(): string {
  return [
    "Usage:",
    "  jumpybrain --version",
    "  jumpybrain instructions",
    '  jumpybrain feedback [--message "..."] [--dry-run] [--id <UUID-v4>] [--json]',
    "  jumpybrain extensions --help",
    "  jumpybrain doctor [--root <memory-root>] [--json] [--check]",
    "  jumpybrain update [--dry-run] [--install-root <path>]",
    "  jumpybrain serve --root <memory-root> --host 127.0.0.1 --port 3787",
    "  jumpybrain run memory:remember --type finding --title \"...\"",
    "  jumpybrain run memory:recall --topic \"...\" --limit 5",
    "  jumpybrain init --root <memory-root>",
    "  jumpybrain migrate obsidian --source <vault> --root <memory-root> [--apply] [--fail-on-conflict] [--json]",
    "  jumpybrain migrate logseq --source <vault> --root <memory-root> [--body-format readable|preserve] [--apply] [--fail-on-conflict] [--json]",
    "  jumpybrain index --root <memory-root> [--rebuild] [--lexical | --semantic-model <absolute-local-path>] [--json]",
    "  jumpybrain index --target-url <url> [--rebuild] [--json] (policy is configured server-local)",
    "  jumpybrain status --root <memory-root> --json",
    "  jumpybrain tree --root <memory-root> [--connections] [--show-files] [--limit 25] [--json]",
    "  jumpybrain recall --root <memory-root> --topic \"...\" --limit 5 --depth shallow",
    "  jumpybrain recall --root <memory-root> --query \"...\" --limit 10 --depth normal --json",
    "  jumpybrain recall --root <memory-root>|--target-url <url> --query \"...\" [--compact [--max-bytes <n>] [--diagnostics]] [--json]",
    "  jumpybrain search --root <memory-root>|--target-url <url> --query \"...\" [--limit 10] [--depth shallow|normal|deep] [--compact [--max-bytes <n>] [--diagnostics]] [--json]",
    "  jumpybrain expand --root <memory-root>|--target-url <url> --id <mem_id> --if-match sha256:<hash> [--start-line <n> --end-line <n> | --section-line <n>] [--max-bytes <n>] [--json]",
    "  jumpybrain delete --root <memory-root>|--target-url <url> --id <mem_id> [--apply --if-match <contentHash>] [--json]",
    "  jumpybrain show --root <memory-root> --id <mem_id> [--json]",
    "  jumpybrain show --target-url <url> --id <mem_id> [--json]",
    "  jumpybrain dream --root <memory-root>|--target-url <url> [--from t-0d|YYYY-MM-DD] [--days 3] [--date-basis evidence|modified] [--offset 0] [--out dream-window.json] [--json]",
    "  jumpybrain dream --root <memory-root>|--target-url <url> --check-sources --id <dream-page-id> [--json]",
    "  cat revised.md | jumpybrain dream --root <memory-root>|--target-url <url> --check-sources --draft --page-file pages/topic.md [--json]",
    "  cat body.md | jumpybrain remember --root <memory-root>|--target-url <url> --type page --dream --title \"Topic map\"",
    "  cat revised.md | jumpybrain update --root <memory-root> --id <mem_id> --if-match <contentHash> [--json]",
    "  cat revised.md | jumpybrain update --target-url <url> --id <mem_id> --if-match <contentHash> [--json]",
    "  delete previews by default; --apply permanently removes one Markdown file. No Trash/Undo; keep backups.",
    "  jumpybrain process --root <memory-root> --mode lint|synthesize|ensure-ids [--topic \"...\"] --apply",
    "  cat memory.md | jumpybrain remember --root <memory-root> --type finding --title \"...\" [--date <ISO-date>]",
    "  cat wrapup.md | jumpybrain wrapup --root <memory-root> --title \"...\" --topic \"...\"",
    "",
    "  recall/search (including recipes): --from <date> --to <date> --reference-date <YYYY-MM-DD> --order relevance|chronological",
    "  Date-only bounds include the day; timestamp uppers exclude it. Relative t-Nd requires --reference-date.",
    "  remember/update: --actor human|agent|unknown [--actor-id <id>] [--actor-name <name>] declares the writer; omitted edits become unknown.",
    "  rich recall/search: --recognition [--last-editor human|agent|unknown|you] [--editor-id <id>] [--edited-from YYYY-MM-DD] [--edited-to YYYY-MM-DD] [--date-field edited|created] [--time-zone <IANA>] [--sort relevance|edited] [--offset <n>] (up to 120 ranked candidates, partial).",
    "  recall/search: --no-refresh skips automatic local index repair; hosted reads never repair.",
    "  recall/search: --read-only forbids derived writes; lexical-only, published closed generation required.",
    "  recall/search (including recipes): --compact [--max-bytes <n>] [--diagnostics]",
    "  Compact and expand: always compact JSON + one LF, no banners; --json is optional.",
    "  maxBytes: 1024-65536 UTF-8 bytes (default 8192), including envelope/diagnostics/LF, not tokens.",
    "  HTTP headers/error packets are outside the successful cap; legacy text/JSON is unchanged.",
  ].join("\n");
}

