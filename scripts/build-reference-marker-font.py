"""Regenerate the tiny, original bracket-only font (optional: pip install fonttools).

No title glyphs are supplied: the writing font renders every other character.
Both brackets have empty outlines and zero advance, preserving literal DOM text
without leaving layout gaps. This is an authoring tool, not a build dependency.
"""
import base64
import io
from pathlib import Path

from fontTools.fontBuilder import FontBuilder
from fontTools.pens.ttGlyphPen import TTGlyphPen

builder = FontBuilder(1000, isTTF=True)
glyphs = [".notdef", "bracketleft", "bracketright"]
builder.setupGlyphOrder(glyphs)
builder.setupCharacterMap({91: "bracketleft", 93: "bracketright"})
builder.setupGlyf({name: TTGlyphPen(None).glyph() for name in glyphs})
builder.setupHorizontalMetrics({name: (0, 0) for name in glyphs})
builder.setupHorizontalHeader(ascent=800, descent=-200)
builder.setupNameTable({"familyName": "JumpyBrain Reference Markers", "styleName": "Regular"})
builder.setupOS2(sTypoAscender=800, sTypoDescender=-200, usWinAscent=800, usWinDescent=200)
builder.setupPost()
builder.font["head"].created = builder.font["head"].modified = 2082844800
builder.font.recalcTimestamp = False
builder.font.flavor = "woff"
output = io.BytesIO()
builder.save(output)
encoded = base64.b64encode(output.getvalue()).decode("ascii")
target = Path(__file__).resolve().parents[1] / "src/adapters/http-server/reference-marker-font.ts"
target.write_text('// Generated by scripts/build-reference-marker-font.py; original zero-width bracket glyphs.\n'
                  f'export const referenceMarkerFont = "{encoded}";\n')
