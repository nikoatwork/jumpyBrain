// Real HTTP server + canonical disposable Markdown. No installed app or real brain.
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { initializeMemoryRoot, indexMemory } from '../dist/runtime/index.js';
import { startJumpyBrainHttpServer } from '../dist/server/index.js';
import { loadPlaywrightChromium, launchPlaywrightChromium } from './playwright-runtime.mjs';
import { appendEditorText, editorMarkdown, selectEditorText, editorSelection, undoEditor } from './editor-smoke-helpers.mjs';
const root = await mkdtemp(path.join(os.tmpdir(), 'jumpybrain-note-find-'));
const output = process.env.JUMPYBRAIN_SMOKE_SCREENSHOT_DIR || '/tmp/jumpybrain-note-find-qa';
const id = 'mem_f1000000-0000-4000-8000-000000000001', second = 'mem_f1000000-0000-4000-8000-000000000002';
const source = `---\nid: ${id}\ntitle: Find fixture\ntype: note\n---\n\nCafé **café** 😀 and [[Page title]].\n\nAnother café match.\n\n${"A separate filler paragraph.\n\n".repeat(60)}Deep needle.\n`;
let browser, server;
try {
  await initializeMemoryRoot(root); await mkdir(output, { recursive: true });
  await writeFile(path.join(root, 'notes/find.md'), source);
  await writeFile(path.join(root, 'notes/second.md'), `---\nid: ${second}\ntitle: Second fixture\ntype: note\n---\n\nOther body.\n`);
  await indexMemory(root, { indexing: { mode: 'lexical' } });
  server = await startJumpyBrainHttpServer({ root, apiKeys: ['find-fixture-key'], port: 0, autoIndex: false });
  browser = await launchPlaywrightChromium({ chromium: await loadPlaywrightChromium() });
  const errors = [];
  for (const width of [1280, 390, 320]) for (const theme of ['dark', 'light']) {
    const context = await browser.newContext({ viewport: { width, height: 850 } });
    const page = await context.newPage(); page.setDefaultTimeout(15000);
    page.on('pageerror', error => errors.push(error.message));
    let puts = 0; page.on('request', request => { if (request.method() === 'PUT') puts++; });
    await page.addInitScript(theme => localStorage.setItem('jumpybrain.theme', theme), theme);
    await page.goto(server.url + '/?note=' + id + '#apiKey=find-fixture-key');
    await page.locator('#note-editor').waitFor({ state: 'visible' });
    const mod = await page.evaluate(() => /Mac|iPhone|iPad/.test(navigator.platform) ? 'Meta' : 'Control');
    const baseline = await editorMarkdown(page);
    await selectEditorText(page, 2); const caret = await editorSelection(page);
    await page.keyboard.press(mod + '+f');
    await page.locator('#note-find-input').fill('café');
    await page.locator('#note-find-count').filter({ hasText: '1 of 3' }).waitFor();
    assert.deepEqual(await page.evaluate(() => [...CSS.highlights.get('note-find')].map(range => range.toString())), ['Café', 'café', 'café']);
    await page.locator('#note-find-input').press('Enter'); assert.equal(await page.locator('#note-find-count').innerText(), '2 of 3');
    await page.locator('#note-find-input').press('Shift+Enter'); assert.equal(await page.locator('#note-find-count').innerText(), '1 of 3');
    await page.locator('#note-find-previous').click(); assert.equal(await page.locator('#note-find-count').innerText(), '3 of 3');
    await page.locator('#note-find-input').fill('not here'); assert.equal(await page.locator('#note-find-count').innerText(), '0 of 0');
    assert.equal(await page.locator('#note-find-next').isDisabled(), true);
    await page.locator('#note-find-input').fill('😀'); assert.equal(await page.locator('#note-find-count').innerText(), '1 of 1');
    await page.locator('#note-find-input').fill('é café'); assert.equal(await page.locator('#note-find-count').innerText(), '1 of 1', 'find crosses inline formatting');
    await page.locator('#note-find-input').fill('[['); assert.equal(await page.locator('#note-find-count').innerText(), '1 of 1', 'literal regex punctuation');
    await page.locator('#note-find-input').fill('Deep needle');
    assert.equal(await page.locator('#note-find-count').innerText(), '1 of 1');
    const scrolled = await page.evaluate(() => ({ bar: document.querySelector('#note-find').getBoundingClientRect().top, match: [...CSS.highlights.get('note-find-current')][0].getBoundingClientRect().top, height: innerHeight }));
    assert.ok(scrolled.bar >= 0 && scrolled.match >= 0 && scrolled.match < scrolled.height, 'match and sticky find stay visible after scrolling');
    await page.locator('#note-find-input').fill('café');
    await page.screenshot({ path: path.join(output, `find-${width}-${theme}.png`) });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.locator('#note-find-input').press('Escape'); assert.equal(await page.locator('#note-find').isHidden(), true);
    assert.deepEqual(await editorSelection(page), caret, 'Escape restores editor caret');
    assert.equal(await editorMarkdown(page), baseline); assert.equal(puts, 0, 'finding never writes');
    assert.equal(await readFile(path.join(root, 'notes/find.md'), 'utf8'), source);
    await page.locator('#note-name').focus();
    await page.keyboard.press(mod + '+f'); await page.locator('#note-find-input').press('Escape');
    assert.equal(await page.locator('#note-name').evaluate(el => document.activeElement === el), true, 'Escape restores title focus without moving the body caret');
    // Shared top-layer labels: hover and keyboard focus, no clipping in a modal.
    await page.locator('[data-format=bold]').hover();
    await page.waitForFunction(() => document.querySelector('#control-label').matches(':popover-open'));
    assert.equal(await page.locator('#control-label').innerText(), 'Bold');
    await page.locator('[data-format=bold]').focus();
    assert.equal(await page.locator('#control-label').innerText(), 'Bold');
    await page.screenshot({ path: path.join(output, `label-${width}-${theme}.png`) });
    await page.locator('#delete-note').click();
    await page.waitForFunction(() => !document.querySelector('#delete-confirm').disabled);
    await page.locator('#delete-cancel').focus();
    await page.screenshot({ path: path.join(output, `delete-${width}-${theme}.png`) });
    assert.doesNotMatch(await page.locator('#document-delete').innerText(), /inbound|relationships|backup|Git/);
    await page.locator('#delete-cancel').click();
    assert.equal(await readFile(path.join(root, 'notes/find.md'), 'utf8'), source);
    await page.locator('#open-search').click();
    await page.locator('#close-search').focus();
    assert.equal(await page.locator('#control-label').innerText(), 'Close search (Esc)');
    const labelBounds = await page.locator('#control-label').boundingBox();
    assert.ok(labelBounds.x >= 0 && labelBounds.x + labelBounds.width <= width, 'top-layer modal label stays within viewport');
    await page.locator('#note-search-input').fill('Find fixture');
    await page.locator('#note-search-input').press(mod + '+f');
    assert.equal(await page.locator('#note-find').isHidden(), true, 'find leaves modal inputs alone');
    assert.equal(await page.locator('#note-search-input').evaluate(el => document.activeElement === el), true);
    await page.locator('#close-search').click();
    // Disabled icons still have pointer labels. No click or mutation is required.
    await page.locator('[data-format=bold]').evaluate(button => { button.disabled = true; });
    await page.locator('[data-format=bold]').hover();
    assert.equal(await page.locator('#control-label').innerText(), 'Bold');
    await page.locator('[data-format=bold]').evaluate(button => { button.disabled = false; });
    if (width === 1280 && theme === 'dark') {
      await page.keyboard.press(mod + '+f'); await page.locator('#note-find-input').fill('café');
      await appendEditorText(page, ' café');
      await page.locator('#note-find-count').filter({ hasText: '1 of 4' }).waitFor();
      await page.keyboard.press('Escape');
      await page.locator('#note-save-state').filter({ hasText: 'Saved' }).waitFor();
      await undoEditor(page);
      await page.waitForFunction(value => richEditor.getMarkdown() === value, baseline);
      await page.locator('#note-save-state').filter({ hasText: 'Saved' }).waitFor();
      await page.keyboard.press(mod + '+f'); await page.locator('#note-find-input').fill('café');
      await page.locator('#open-search').click(); await page.locator('#note-search-input').fill('Second fixture');
      await page.locator('#search-results strong').filter({ hasText: 'Second fixture' }).waitFor();
      await page.locator('#note-search-input').press('Enter');
      await page.waitForURL('**/?note=' + second);
      assert.equal(await page.locator('#note-find').isHidden(), true);
      assert.equal(await page.evaluate(() => CSS.highlights.has('note-find')), false);
      await writeFile(path.join(root, 'notes/find.md'), source);
    }
    await context.close(); console.log(`PASS note find/labels/delete ${width}px ${theme}`);
  }
  assert.deepEqual(errors, []);
  console.log('PASS find count/navigation/Unicode/format spans/literal query/Escape/caret/history/live edits/note switch, immutable canonical reads, modal isolation and shared labels. Screenshots: ' + output);
} finally { await browser?.close(); await server?.close(); await rm(root, { recursive: true, force: true }); }
